export const DICTIONARY_WORDS: string[] = Array.from(DICTIONARY_SET);

// Standard common morphological suffixes to recognize natural inflections of valid base words
const INFLECTION_RULES: Array<{ suffix: string; strip: number; add?: string }> = [
  { suffix: 'IES', strip: 3, add: 'Y' },
  { suffix: 'IED', strip: 3, add: 'Y' },
  { suffix: 'IER', strip: 3, add: 'Y' },
  { suffix: 'IEST', strip: 4, add: 'Y' },
  { suffix: 'ING', strip: 3 },
  { suffix: 'ING', strip: 3, add: 'E' },
  { suffix: 'ED', strip: 2 },
  { suffix: 'ED', strip: 1 },
  { suffix: 'ER', strip: 2 },
  { suffix: 'ER', strip: 1 },
  { suffix: 'EST', strip: 3 },
  { suffix: 'EST', strip: 2 },
  { suffix: 'LY', strip: 2 },
  { suffix: 'ES', strip: 2 },
  { suffix: 'S', strip: 1 },
];

/**
 * Checks if a cleaned uppercase word is a genuine English word
 * (rejecting gibberish like AAAAA, QXZRT, BBBB, etc.).
 */
export function isValidEnglishWord(
  word: string,
  globalCategory: GlobalWordCategory = 'ALL'
): boolean {
  if (!word || word.length < 3 || word.length > 18) return false;
  if (!/^[A-Z]+$/.test(word)) return false;

  // Reject 3+ identical consecutive letters (e.g., AAAA, ZZZ)
  if (/(.)\1\1/.test(word)) return false;

  // Must contain at least one vowel or Y
  if (!/[AEIOUY]/.test(word)) return false;

  const targetSet =
    globalCategory === 'ALL' ? DICTIONARY_SET : CATEGORY_SETS[globalCategory];

  if (targetSet.has(word)) return true;

  // Check standard morphological inflections against the target set
  for (const rule of INFLECTION_RULES) {
    if (word.length > rule.strip + 2 && word.endsWith(rule.suffix)) {
      const stem = word.slice(0, -rule.strip) + (rule.add ?? '');
      if (targetSet.has(stem)) return true;
      // Handle doubled final consonant (e.g. RUNNING -> RUN, STOPPED -> STOP)
      if (
        (rule.suffix === 'ING' || rule.suffix === 'ED' || rule.suffix === 'ER') &&
        stem.length >= 3 &&
        stem[stem.length - 1] === stem[stem.length - 2]
      ) {
        if (targetSet.has(stem.slice(0, -1))) return true;
      }
    }
  }

  return false;
}

export function getDictionaryForCategory(category: GlobalWordCategory): string[] {
  if (category === 'ALL') return DICTIONARY_WORDS;
  return CATEGORY_ARRAYS[category];
}

